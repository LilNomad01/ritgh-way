do $security$
declare table_name text;
begin
  foreach table_name in array array[
    'students', 'course_modules', 'course_sections', 'lessons',
    'lesson_exercises', 'user_accounts', 'auth_sessions', 'login_attempts',
    'placement_attempts', 'lesson_progress', 'exercise_attempts',
    'practice_sessions', 'video_progress', 'section_exams',
    'section_exam_questions', 'section_exam_attempts', 'lesson_videos',
    'video_item_progress', 'speaking_attempts'
  ] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
    execute format('grant all on table public.%I to service_role', table_name);
  end loop;
end
$security$;

