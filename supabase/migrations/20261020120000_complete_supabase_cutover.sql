do $flags$
declare column_type text;
begin
  select data_type into column_type from information_schema.columns where table_schema = 'public' and table_name = 'user_accounts' and column_name = 'must_change_password';
  if column_type = 'boolean' then
    alter table public.user_accounts alter column must_change_password drop default;
    alter table public.user_accounts alter column must_change_password type smallint using case when must_change_password then 1 else 0 end;
    alter table public.user_accounts alter column must_change_password set default 0;
  end if;

  select data_type into column_type from information_schema.columns where table_schema = 'public' and table_name = 'section_exam_attempts' and column_name = 'passed';
  if column_type = 'boolean' then
    alter table public.section_exam_attempts alter column passed drop default;
    alter table public.section_exam_attempts alter column passed type smallint using case when passed then 1 else 0 end;
    alter table public.section_exam_attempts alter column passed set default 0;
  end if;
end
$flags$;

create table if not exists public.lesson_videos (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  video_key text not null,
  title text not null,
  size bigint not null default 0 check (size >= 0),
  position integer not null default 0,
  start_seconds integer not null default 0 check (start_seconds >= 0),
  end_seconds integer check (end_seconds is null or end_seconds >= start_seconds)
);

create table if not exists public.video_item_progress (
  user_id bigint not null references public.user_accounts(id) on delete cascade,
  video_id bigint not null references public.lesson_videos(id) on delete cascade,
  position_seconds integer not null default 0 check (position_seconds >= 0),
  duration_seconds integer not null default 0 check (duration_seconds >= 0),
  completed smallint not null default 0 check (completed in (0, 1)),
  updated_at timestamptz not null default now(),
  primary key (user_id, video_id)
);

create table if not exists public.speaking_attempts (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.user_accounts(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  exercise_id bigint not null references public.lesson_exercises(id) on delete cascade,
  practice_session_id bigint not null references public.practice_sessions(id) on delete cascade,
  attempt_number integer not null default 1 check (attempt_number > 0),
  transcription text not null,
  expected_text text not null,
  conceptual_status text not null,
  conceptual_score integer check (conceptual_score between 0 and 100),
  vocabulary_score integer check (vocabulary_score between 0 and 100),
  grammar_score integer check (grammar_score between 0 and 100),
  pronunciation_score integer check (pronunciation_score between 0 and 100),
  fluency_score integer check (fluency_score between 0 and 100),
  result_json text not null,
  provider text not null,
  status text not null default 'completed',
  created_at timestamptz not null default now()
);

