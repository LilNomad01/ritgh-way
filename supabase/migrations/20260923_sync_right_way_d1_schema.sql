-- Advance identity/serial sequences after imported rows so future inserts never reuse an existing id.
do $$
declare
  table_name text;
  sequence_name text;
  maximum_id bigint;
begin
  foreach table_name in array array[
    'students','course_modules','course_sections','lessons','lesson_exercises',
    'user_accounts','placement_attempts','lesson_progress','exercise_attempts',
    'practice_sessions','video_progress','section_exams','section_exam_questions',
    'section_exam_attempts','lesson_videos'
  ]
  loop
    sequence_name := pg_get_serial_sequence(format('public.%I', table_name), 'id');
    if sequence_name is not null then
      execute format('select coalesce(max(id), 0) from public.%I', table_name) into maximum_id;
      perform setval(sequence_name, greatest(maximum_id, 1), maximum_id > 0);
    end if;
  end loop;
end $$;
