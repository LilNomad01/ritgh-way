-- Keep direct REST access closed. The Vercel server connects with the database credential.
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'students','course_modules','course_sections','lessons','lesson_exercises',
    'user_accounts','auth_sessions','login_attempts','placement_attempts',
    'lesson_progress','exercise_attempts','practice_sessions','video_progress',
    'section_exams','section_exam_questions','section_exam_attempts',
    'lesson_videos','video_item_progress'
  ]
  loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from anon, authenticated', table_name);
  end loop;
end $$;

