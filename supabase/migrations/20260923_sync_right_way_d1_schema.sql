-- The live app stores booleans as 0/1. Convert only these Right Way columns if the old foundation used PostgreSQL booleans.
do $$
begin
  if exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='user_accounts'
      and column_name='must_change_password' and data_type='boolean'
  ) then
    alter table public.user_accounts
      alter column must_change_password drop default,
      alter column must_change_password type integer using (case when must_change_password then 1 else 0 end),
      alter column must_change_password set default 0;
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema='public' and table_name='section_exam_attempts'
      and column_name='passed' and data_type='boolean'
  ) then
    alter table public.section_exam_attempts
      alter column passed drop default,
      alter column passed type integer using (case when passed then 1 else 0 end),
      alter column passed set default 0;
  end if;
end $$;

